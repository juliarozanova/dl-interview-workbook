"""Generate the companion Python package from the chapter Markdown (single source of truth).

companion/
  conftest.py                         puts companion/ on sys.path
  exercises/chNN/<ex_id>.py           YOUR workspace: written once from :::starter, never overwritten
  solutions/chNN/<ex_id>.py           regenerated every build from :::solution
  tests/chNN/test_<ex_id>.py          regenerated every build from :::tests

Tests import from `exercises` by default; `WB_IMPL=solutions` points them at the reference.
"""

from __future__ import annotations

from pathlib import Path

from parse import Exercise

ROOT = Path(__file__).resolve().parent.parent
COMPANION = ROOT / "companion"

CONFTEST = '''"""Generated by build/companion.py. Makes `exercises` / `solutions` importable from anywhere."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
'''

TEST_HEADER = '''# Generated from {source} by `make build`. Do not edit: changes are overwritten.
# Runs against companion/exercises by default; WB_IMPL=solutions checks the reference instead.
import importlib
import os

_impl = importlib.import_module(f"{{os.environ.get('WB_IMPL', 'exercises')}}.{chapter}.{module}")
globals().update({{k: v for k, v in vars(_impl).items() if not k.startswith("__")}})

'''


def module_name(ex: Exercise) -> str:
    return ex.id.replace("-", "_")


def paths(chapter_num: str, ex: Exercise) -> dict | None:
    """Repo-relative paths for an exercise, or None if it has no runnable workspace."""
    if not (ex.get("starter") and ex.get("tests")):
        return None
    ch, mod = f"ch{int(chapter_num):02d}", module_name(ex)
    return {
        "chapter": ch,
        "module": mod,
        "file": f"companion/exercises/{ch}/{mod}.py",
        "solution": f"companion/solutions/{ch}/{mod}.py",
        "test": f"companion/tests/{ch}/test_{mod}.py",
    }


def _package(d: Path) -> None:
    d.mkdir(parents=True, exist_ok=True)
    (d / "__init__.py").touch()


def write(chapter_num: str, ex: Exercise, source: str) -> dict | None:
    p = paths(chapter_num, ex)
    if p is None:
        return None
    COMPANION.mkdir(exist_ok=True)
    (COMPANION / "conftest.py").write_text(CONFTEST)
    for kind in ("exercises", "solutions"):
        _package(COMPANION / kind)
        _package(COMPANION / kind / p["chapter"])
    (COMPANION / "tests" / p["chapter"]).mkdir(parents=True, exist_ok=True)

    workspace = ROOT / p["file"]
    if not workspace.exists():  # never clobber the user's work
        workspace.write_text(ex.get("starter").body + "\n")
    (ROOT / p["solution"]).write_text(f"# Generated from {source}. Do not edit.\n" + ex.get("solution").body + "\n")
    header = TEST_HEADER.format(source=source, chapter=p["chapter"], module=p["module"])
    (ROOT / p["test"]).write_text(header + ex.get("tests").body + "\n")
    return p
